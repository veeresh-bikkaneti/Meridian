// build-attempt-queue.mjs — deterministic generation ATTEMPT order
// for the remaining pool candidates.
//
// Run: node scripts/clues/production/build-attempt-queue.mjs
//
// Why this exists (Wave 1 calibration finding): fame-order attempts
// over ranks 1-200 yielded 3 accepted / 195 climate rejections,
// because the crawl cache's lead excerpts rarely contain climate
// material (only ~12% of above-floor candidates carry any climate-
// signal token, and a token is necessary — not sufficient — for the
// prompt's tier-2 mechanism/extreme/paradox bar). Attempting the
// remaining 10,445 candidates in pure fame order would spend most
// worker effort on extracts that cannot pass tier 2.
//
// Attempt order (deterministic; SEQUENCING ONLY — nothing is
// excluded, no rule changes):
//   1. Unattempted candidates whose extract carries a climate signal
//      (validator hasClimateSignal, root-prefix), in fame rank order.
//   2. All other unattempted candidates, in fame rank order.
// Assembly/publication order is always pure fame rank (assemble.mjs
// sorts by pool rank), so attempt sequencing cannot bias the
// published set's ordering — only the order in which places are tried.
//
// Reads:  pool.jsonl, records.jsonl (already-attempted place_ids)
// Writes: attempt-queue.jsonl (§9 inputs in attempt order),
//         attempt-order.md (counts + this rationale)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { hasClimateSignal } from "../validate-clues.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));

function readJsonLines(path) {
  return readFileSync(path, "utf8").split("\n").filter((l) => l.trim()).map((l) => JSON.parse(l));
}

function main() {
  const pool = readJsonLines(join(HERE, "pool.jsonl"));
  let attempted = new Set();
  try {
    attempted = new Set(readJsonLines(join(HERE, "records.jsonl")).map((r) => r.place_id));
  } catch {
    attempted = new Set();
  }
  const remaining = pool.filter((input) => !attempted.has(input.place.place_id));
  const signal = remaining.filter((input) => hasClimateSignal(input.extracts[0].text));
  const signalIds = new Set(signal.map((i) => i.place.place_id));
  const rest = remaining.filter((input) => !signalIds.has(input.place.place_id));
  const queue = [...signal, ...rest];

  writeFileSync(join(HERE, "attempt-queue.jsonl"), queue.map((i) => JSON.stringify(i)).join("\n") + "\n");
  const md = `# Attempt order — GeoDetective Phase 2 production pass

Generated by \`scripts/clues/production/build-attempt-queue.mjs\`
(deterministic; re-running reproduces attempt-queue.jsonl exactly
from pool.jsonl + records.jsonl).

## Counts

| Set | Count |
|---|---|
| Pool candidates (all above the substance floor) | ${pool.length} |
| Already attempted (in records.jsonl) | ${attempted.size} |
| Remaining | ${remaining.length} |
| Remaining with a climate-signal token in the extract | ${signal.length} |
| Remaining without | ${rest.length} |

## Order

1. Remaining climate-signal candidates, in pool fame-rank order.
2. All other remaining candidates, in pool fame-rank order.

Sequencing only: no candidate is excluded and no validation rule
changes. Publication order in \`public/loop/\` is always pool fame
rank, independent of attempt order.

## Why (Wave 1 evidence)

Wave 1 attempted pool ranks 1-200 in fame order: 3 accepted, 195
rejected at tier 2 (climate), 2 rejected on reading level. The crawl
cache's extracts are one-sentence-hook lead excerpts; most never
mention weather. The prompt (locked) requires a tier-2 climate
mechanism, extreme, or paradox verbatim-traceable to the extract —
so candidates whose extracts carry climate material are attempted
first. A climate-signal token does not guarantee acceptance (the
bar is substantive: bare classifications and average temperatures
do not qualify, as Wave 1 spot-checks confirmed).
`;
  writeFileSync(join(HERE, "attempt-order.md"), md);
  console.log(
    JSON.stringify(
      { pool: pool.length, attempted: attempted.size, remaining: remaining.length, signal: signal.length, rest: rest.length },
      null,
      2,
    ),
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main();
}
